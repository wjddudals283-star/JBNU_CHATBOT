"""자족성 — 혼자 떼어놨을 때 뜻이 서는가.

★ 축은 길이가 아니다
  길이 정규화를 세 번 시도해서 세 번 졌다 (0.6/1.2/2.0 → 78/76/72%).

      '준공년도 : 1995년'      11자   혼자서 뜻이 선다
      '여성건강간호학교실'        9자   이름뿐이다

  길이는 둘을 못 가른다. 가르는 건 이름만 있느냐, 이름과 값이 같이 있느냐다.

여기 있는 예문은 전부 **실제 코퍼스에서 뽑은 것**이다.
지어낸 문장으로 시험하면 지어낸 규칙을 검증하게 된다.
"""

from __future__ import annotations

import pytest

from skill.selfcontained import is_self_contained, why

# 20자 이하 잎을 뽑아 눈으로 갈랐다 (71,815개 중 표본)
조각 = [
    "상세보기", "자세히보기", "All", "바로가기",
    "고전문학사", "통계적사고와사회",          # 과목 이름 — 이름표다
    "여성건강간호학교실", "AI융합대학원", "외국학술지지원센터",
    "참가신청", "발전계획 발전계획", "공연ㆍ전시",
    "1", "1-2", "13",                        # 표 셀 숫자
    "가. 사회봉사", "월간 일정", "사유 발생시",
    "고규진 자세히보기",
]

자족 = [
    "출판사 | : Miller Pub.", "준공년도 : 1995년", "판독비용 | 무료",
    "인문(영어영문) | 800점 이상", "토 ~ 일요일(공휴일) : 휴실",
    "김원기 | 법전원 교수", "성명 | 김지훈",
    "1종 장학금 : 등록금 전액", "군휴학 : 군입대 일자 입력",
    "매 학기 개강 6주 전부터 가능함 (단, 군입대 휴학과 임신.출산.육아 휴학은 수시 가능)",
    "OASIS에서 신분변동사항 입력 후 관련 증빙서류 첨부",
    "학장이 승인한 후 총장이 최종 허가",
    "100(2012년도 입학자까지 적용)",
]


@pytest.mark.parametrize("t", 조각)
def test_조각은_걸러진다(t):
    assert not is_self_contained(t), f"{t!r} 를 자족으로 봤다 ({why(t)})"


@pytest.mark.parametrize("t", 자족)
def test_자족문은_통과한다(t):
    assert is_self_contained(t), f"{t!r} 를 조각으로 봤다 ({why(t)})"


def test_의존명사를_서술어로_보면_안_된다():
    """처음에 '시·중·간·내·후·전·것' 을 종결어미에 넣었다가 걸렸다.

    '~할 시' 는 '언제' 를 뜻하는 의존명사다. 혼자서는 뜻이 서지 않는 쪽이고,
    **자족성의 반대**다. 종결어미와 모양만 같다.
    """
    for t in ("사유 발생시", "공연ㆍ전시", "신청 기간 중", "입학 전"):
        assert not is_self_contained(t), f"{t!r} ({why(t)})"


def test_길이로는_못_가른다():
    """이 두 개가 길이 정규화가 세 번 진 이유다."""
    assert is_self_contained("준공년도 : 1995년")      # 11자
    assert not is_self_contained("여성건강간호학교실")     # 9자


def test_왜_그렇게_봤는지_말한다():
    """판정을 못 믿겠을 때 근거를 볼 수 있어야 한다."""
    assert why("준공년도 : 1995년") == "이름:값 쌍"
    assert why("1-2") == "숫자·기호뿐"
    assert "이름뿐" in why("고전문학사")


def test_빈_값에도_안_죽는다():
    for t in ("", "   ", None):
        assert not is_self_contained(t)
