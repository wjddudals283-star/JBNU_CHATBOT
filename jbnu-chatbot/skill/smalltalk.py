"""인사·잡담을 검색에 태우지 않는다.

★ 왜 필요해졌나
  폴백 블록을 검색으로 연결하면 학생이 **아무 말이나** 보낼 수 있게 된다.
  그게 목적이다 — 발화 6개로는 6,985페이지가 안 쓰인다.
  대신 질문이 아닌 말까지 검색기에 들어온다.

    '오늘 뭐해'  →  '뭐해' 가 어딘가에 스쳐서  →  listCard '연설문'
  질문이 아닌 말에 자료를 들이미는 건 아는 척이다.

★ 왜 목록을 손으로 쓰나 (하드코딩 아닌가)
  손으로 쓰지 않기로 한 것은 **학교에 대한 관측**이다 — 어느 학과가 무슨
  제도를 쓰는지, 어떤 제목이 같은 뜻인지. 그건 사이트가 답을 갖고 있다.
  인사말은 학교 사이트에 없다. 관측할 대상이 아니라 대화의 표면이다.

★ 문장 전체로만 맞춘다 — 이게 안전장치다
  낱말이 들어 있는지로 보면 '밥 뭐야' 가 잡담으로 먹힌다. 그건 진짜 질문이다.
  정규화한 **문장 전체**가 목록과 같을 때만 잡담으로 본다.
  그러면 목록에 없는 말은 전부 검색으로 간다 — 틀려도 안전한 쪽으로 틀린다.
"""

from __future__ import annotations

import re

# 문장 전체가 이것과 같을 때만 잡담이다 (부분 일치 아님)
GREETING = {
    "안녕", "안녕하세요", "안녕하십니까", "하이", "헬로", "hi", "hello",
    "반가워", "반갑습니다", "안녕하세요반갑습니다",
}

CHITCHAT = {
    "오늘뭐해", "뭐해", "뭐하니", "뭐하냐", "심심해", "놀자", "사랑해",
    "누구야", "너누구야", "넌누구야", "이름이뭐야", "너뭐야",
    "밥먹었어", "잘자", "굿나잇", "바보", "멍청이",
}

THANKS = {"고마워", "감사합니다", "감사해요", "고맙습니다", "ㄱㅅ", "땡큐", "thanks"}

# ㅋㅋㅋ · ㅎㅎ · ㅠㅠ · ... 처럼 같은 글자만 반복되는 것
_REPEAT = re.compile(r"^([ㄱ-ㅎㅏ-ㅣ.!?~ㅜㅠ])\1*$")


def _norm(s: str) -> str:
    return re.sub(r"[\s.,!?~^;:'\"()\-]+", "", (s or "")).lower()


def classify(utterance: str) -> str | None:
    """'greeting' | 'chitchat' | 'thanks' | None(질문일 수 있음)."""
    s = _norm(utterance)
    if not s:
        return None
    if s in GREETING:
        return "greeting"
    if s in THANKS:
        return "thanks"
    if s in CHITCHAT or _REPEAT.match(s):
        return "chitchat"
    return None


def response(kind: str) -> dict:
    """카카오 스킬 응답.

    ★ 인사에 인사만 하고 끝내지 않는다.
      학생은 대개 뭘 물어도 되는지 몰라서 인사부터 한다.
      무엇을 물을 수 있는지 같이 알려주는 것이 답이다.
    """
    head = {
        "greeting": "안녕하세요! 전북대 총학생회 챗봇이에요.",
        "chitchat": "저는 학교 안내를 찾아드리는 챗봇이에요.",
        "thanks": "도움이 됐다니 다행이에요!",
    }[kind]
    text = (
        f"{head}\n\n"
        "학교 홈페이지에 올라온 내용을 찾아서 **그대로** 보여드려요.\n"
        "이렇게 물어봐 주세요.\n\n"
        "· 휴학 신청 방법\n"
        "· 졸업 몇 학점이야\n"
        "· 국가장학금 신청 기간\n"
        "· 오늘 학식\n\n"
        "모르는 건 모른다고 말씀드릴게요."
    )
    return {"version": "2.0", "template": {"outputs": [{"simpleText": {"text": text}}]}}
