"""혼자 떼어놨을 때 뜻이 서는가 — 인용 단위와 랭킹에 같은 잣대를 쓴다.

★ 왜 길이가 아니라 이건가
  길이 정규화를 세 번 시도해서 세 번 졌다 (0.6/1.2/2.0 → 78/76/72%).
  축이 틀렸다. 짧아서 나쁜 게 아니다.

      '준공년도 : 1995년'      11자   혼자서 뜻이 선다 → 살려야 한다
      '여성건강간호학교실'        9자   이름뿐이다      → 죽여야 한다

  길이는 둘을 못 가른다. 가르는 건 **이름만 있느냐, 이름과 값이 같이 있느냐**다.

★ 관측에서 나왔다 (하드코딩이 아니다)
  20자 이하 잎을 뽑아 보니 모양이 두 갈래로 갈렸다.
      자족  '출판사 | : Miller Pub.' · '판독비용 | 무료' · '인문(영어영문) | 800점 이상'
            '토 ~ 일요일(공휴일) : 휴실' · '김원기 | 법전원 교수'
      조각  '상세보기' · '자세히보기' · 'All' · '고전문학사' · '참가신청' · '발전계획 발전계획'
  자족적인 쪽은 전부 구분자로 이름과 값이 붙어 있었다. 조각은 이름뿐이었다.

★ 종결어미 목록은 손으로 썼다 — 그건 학교 관측이 아니라 한국어 표면이다
  학교 사이트가 답을 갖고 있는 것(어느 학과가 무슨 제도를 쓰는지, 어떤 제목이
  같은 뜻인지)은 손으로 쓰지 않는다. 어미는 사이트에 없다. smalltalk 과 같은 이유다.

★ 이 잣대를 두 곳에 같이 쓴다
  인용 — 조각이면 인용하지 않고 자족적인 조상까지 올린다
  랭킹 — 조각인 잎은 1등이 될 수 없다
  한쪽만 고치면 '좋은 걸 골라 놓고 조각을 인용' 하거나 그 반대가 된다.
"""

from __future__ import annotations

import re

# 이름과 값을 잇는 구분자. 표·정의목록이 이 모양으로 들어온다.
_PAIR = re.compile(r"[^\s:|][^\n]*[:|]\s*\S")

# 서술어로 끝나면 문장이다. 한국어 표면이지 학교 관측이 아니다.
#
# ★ 의존명사(것·중·간·내·후·전·시)는 넣지 않는다 — 처음엔 넣었다가 걸렸다
#     '사유 발생시' · '공연ㆍ전시'  →  '시' 로 끝난다고 서술어로 오판
#   '~할 시' 는 '언제' 를 뜻하는 의존명사다. 혼자서는 뜻이 서지 않는 쪽이고,
#   자족성의 반대다. 종결어미와 모양만 같다.
_PREDICATE = re.compile(
    r"(다|함|됨|음|임|요|까|바람|가능|불가|필요|없음|있음"
    r"|한다|된다|합니다|됩니다|입니다|하세요|하십시오|바랍니다)\s*[.!?)\]]*$")

# 숫자·기호만 (표 셀에서 자주 나온다: '1' · '1-2' · '13')
_SYMBOLIC = re.compile(r"^[\d\s.,\-~/()%]+$")

# 링크 텍스트. 어느 사이트에나 있고 아무 뜻이 없다.
# ★ 이건 보일러플레이트 탐지가 관측으로 잡아 주는 게 원칙이지만,
#   잎 단위로 남은 것이 있어 여기서 한 번 더 거른다.
_NAVI = re.compile(r"^(상세|자세히|더)?\s*보기$|^(바로가기|더보기|목록|이전|다음|All)$")

MIN_CHARS = 12          # 이 아래는 이름·값 쌍이나 서술어가 있어야 산다
MIN_WORDS = 3


def _clean(text: str) -> str:
    return re.sub(r"\s+", " ", (text or "")).strip()


def is_self_contained(text: str) -> bool:
    """혼자 떼어놨을 때 뜻이 서는가."""
    t = _clean(text)
    if not t or _SYMBOLIC.match(t) or _NAVI.match(t):
        return False
    if _PAIR.search(t):             # 이름 : 값  /  이름 | 값
        return True
    if _PREDICATE.search(t):        # 서술어로 끝난다
        return True
    # 구분자도 서술어도 없으면 이름일 가능성이 높다.
    # 충분히 길고 어절이 여럿이면 그래도 뜻이 선다고 본다.
    return len(t) >= MIN_CHARS and len(t.split()) >= MIN_WORDS


def why(text: str) -> str:
    """왜 그렇게 봤는지. 진단용 — 판정을 못 믿겠을 때 근거를 본다."""
    t = _clean(text)
    if not t:
        return "빈 문자열"
    if _SYMBOLIC.match(t):
        return "숫자·기호뿐"
    if _NAVI.match(t):
        return "링크 텍스트"
    if _PAIR.search(t):
        return "이름:값 쌍"
    if _PREDICATE.search(t):
        return "서술어 종결"
    if len(t) >= MIN_CHARS and len(t.split()) >= MIN_WORDS:
        return f"{len(t)}자 {len(t.split())}어절"
    return f"이름뿐 ({len(t)}자 {len(t.split())}어절)"
